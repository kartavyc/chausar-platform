export function hostMessage(language: Language, key: HostTextKey, values: Readonly<Record<string, string>> = {}): string {
  const template = language === 'hi' ? HI[key] : EN[key];
  return template.replace(/\{([A-Za-z]+)\}/g, (placeholder, name: string) => values[name] ?? placeholder);
}

/** Reuse the finalized catalogue's seven categorical missing words. */
export function hostMissingWords(language: Language): MissingWords {
  const catalogue = language === 'hi' ? hi : en;
  return {
    absent: catalogue['MISSING.absent'],
    null: catalogue['MISSING.null'],
    unknown: catalogue['MISSING.unknown'],
    withheld: catalogue['MISSING.withheld'],
    'not-applicable': catalogue['MISSING.not-applicable'],
    'not-loaded-yet': catalogue['MISSING.not-loaded-yet'],
    'not-counted': catalogue['MISSING.not-counted'],
  };
}
