import test from 'node:test';
import assert from 'node:assert/strict';
import { VENTURE_ERRORS } from '../runtime/venture/contracts.ts';
import { setup, owner } from './venture-views-env.ts';
import { SEO_VISIBILITY_DESK } from '../runtime/venture/playbooks/seo-visibility/desk.ts';
import { sweepWholeJournal } from '../runtime/venture/build/journal-sweep.ts';
import { runWebsiteRechecksDue } from '../runtime/venture/playbooks/seo-visibility/site-recheck.ts';
const base = { playbook: 'seo-visibility' as const, kind: 'website' };
const report = (revision = 1) => ({ url: 'https://clinic.example/', revision, runs: [390, 1280].flatMap(width => ['light', 'dark'].map(colorScheme => ({ viewport: { width, height: 900 }, colorScheme }))), findings: [] });
async function scheduled() { const env = await setup(); const handler = SEO_VISIBILITY_DESK.website!; const made: any = await handler.act!(env.deps, owner, { ...base, id: 'new', action: 'import', payload: { url: report().url, report: report() } }); let view: any = await handler.get!(env.deps, owner, { ...base, id: made.id }); await handler.act!(env.deps, owner, { ...base, id: made.id, action: 'approve', payload: {}, digest: view.digest }); view = await handler.get!(env.deps, owner, { ...base, id: made.id }); await handler.act!(env.deps, owner, { ...base, id: made.id, action: 'schedule', payload: {}, digest: view.digest }); return { env, handler, id: made.id, prior: view.item.report.receipt }; }
test('the real due tick runs the checker and stores an unapproved report compared with the last hash', async () => {
    const { env, handler, id, prior } = await scheduled();
    let calls = 0;
    env.deps.net = { resolve: async () => [{ address: '93.184.216.34', family: 4 }], send: async () => ({ status: 200, headers: {}, body: Buffer.from('User-agent: *\nAllow: /') }) };
    env.deps.seoWebsiteChecker = { async run(url) { calls++; assert.equal(url, report().url); return report(calls + 1); } };
    await runWebsiteRechecksDue(env.deps, owner);
    assert.equal(calls, 0);
    env.advance(30 * 86400000);
    await sweepWholeJournal(env.deps, owner);
    assert.equal(calls, 1);
    const rows: any = (await handler.list!(env.deps, owner, base)).rows;
    assert.equal(rows.length, 2);
    const fresh = rows.find((row: any) => row.id !== id);
    assert.equal(fresh.report.previousReceipt, prior);
    assert.notEqual(fresh.report.receipt, prior);
    assert.equal(fresh.report.approved, false);
    let view: any = await handler.get!(env.deps, owner, { ...base, id });
    assert.equal(view.item.recheck.latestReportId, fresh.id);
    assert.equal(view.item.recheck.latestReceipt, fresh.report.receipt);
    env.advance(30 * 86400000);
    await sweepWholeJournal(env.deps, owner);
    assert.equal(calls, 2);
    const nextRows: any = (await handler.list!(env.deps, owner, base)).rows;
    const latest = nextRows.at(-1);
    assert.equal(latest.report.previousReceipt, fresh.report.receipt);
    assert.equal(latest.report.approved, false);
    view = await handler.get!(env.deps, owner, { ...base, id });
    await handler.act!(env.deps, owner, { ...base, id, action: 'stop-recheck', payload: {}, digest: view.digest });
    env.advance(30 * 86400000);
    await sweepWholeJournal(env.deps, owner);
    assert.equal(calls, 2);
});
test('a missing installed checker pauses the approved job without inventing a fresh report', async () => {
    const { env, handler, id } = await scheduled();
    env.deps.seoWebsiteChecker = null;
    env.advance(30 * 86400000);
    await runWebsiteRechecksDue(env.deps, owner);
    const view: any = await handler.get!(env.deps, owner, { ...base, id });
    assert.equal(view.item.recheck.state, 'held');
    assert.equal(view.item.recheck.error, 'SITE_CHECK_PLANNED');
    assert.ok((VENTURE_ERRORS as readonly string[]).includes(view.item.recheck.error), 'the actual public refusal stays in the declared error contract');
    assert.equal((await handler.list!(env.deps, owner, base)).rows.length, 1);
    await runWebsiteRechecksDue(env.deps, owner);
    assert.equal((await handler.get!(env.deps, owner, { ...base, id })).digest, view.digest);
});
test('Stop aborts the in-flight checker and a later schedule cannot receive the old completion', async () => {
    const { env, handler, id } = await scheduled();
    env.advance(30 * 86400000);
    env.deps.net = { resolve: async () => [{ address: '93.184.216.34', family: 4 }], send: async () => ({ status: 200, headers: {}, body: Buffer.from('User-agent: *\nAllow: /') }) };
    let unblock!: () => void;
    const blocked = new Promise<void>(resolve => { unblock = resolve; });
    let reached!: () => void;
    const started = new Promise<void>(resolve => { reached = resolve; });
    let signal: AbortSignal | undefined;
    env.deps.seoWebsiteChecker = { async run(_url, abort) { signal = abort; reached(); await blocked; return report(2); } };
    const running = runWebsiteRechecksDue(env.deps, owner);
    await started;
    let view: any = await handler.get!(env.deps, owner, { ...base, id });
    await handler.act!(env.deps, owner, { ...base, id, action: 'stop-recheck', payload: {}, digest: view.digest });
    const wasAborted = signal?.aborted;
    view = await handler.get!(env.deps, owner, { ...base, id });
    await handler.act!(env.deps, owner, { ...base, id, action: 'schedule', payload: {}, digest: view.digest });
    unblock();
    await running;
    const after: any = await handler.get!(env.deps, owner, { ...base, id });
    assert.equal(wasAborted, true);
    assert.equal(after.item.recheck.state, 'active');
    assert.equal(after.item.recheck.error, null);
    assert.equal((await handler.list!(env.deps, owner, base)).rows.length, 1);
});
