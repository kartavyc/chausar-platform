#!/usr/bin/env node
// D11: one place for each flag. Reads platform/runtime/config/env.ts and writes .env.example (the CHAUSAR_* names
// someone running Chausar from source may set, every value empty) and docs/configuration.md (every name). --check
// compares both files and also scans the source: a CHAUSAR_* name that source reads and the list lacks fails by name.
// Usage: node scripts/env-docs.mjs --write | --check
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.argv.slice(2);
if (mode.length !== 1 || !['--write', '--check'].includes(mode[0])) {
  process.stderr.write('Usage: node scripts/env-docs.mjs --write | --check\n');
  process.exit(2);
}
const { ENV, NOT_ENV } = await import(pathToFileURL(join(root, 'platform', 'runtime', 'config', 'env.ts')).href);

/** Where source may read a variable. Tests, fixtures and the generated files are not source. */
const AREAS = ['platform/runtime', 'app/desktop', 'app/ui/src', 'scripts', '.github/workflows'];
const SKIP_FILES = new Set(['platform/runtime/config/env.ts', 'scripts/env-docs.mjs']);
const SOURCE = /\.(?:ts|tsx|mts|cts|mjs|cjs|js|jsx|ya?ml)$/;

async function walk(folder) {
  const found = [];
  for (const entry of await readdir(folder, { withFileTypes: true }).catch(() => [])) {
    const path = join(folder, entry.name);
    if (entry.isDirectory()) { if (!['node_modules', 'fixtures', 'dist', 'tests'].includes(entry.name)) found.push(...await walk(path)); }
    else if (SOURCE.test(entry.name) && !/\.test\.[a-z]+$/.test(entry.name)) found.push(path);
  }
  return found;
}

const generatedNote = 'Generated by scripts/env-docs.mjs from platform/runtime/config/env.ts. Edit that list, then run node scripts/env-docs.mjs --write.';
const html = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('|', '\\|');

function exampleText() {
  const lines = [`# ${generatedNote}`, '# The variables someone running Chausar from source may set. All are optional; docs/configuration.md lists every one.',
    '# A data folder must be an absolute path outside the code folder. Secrets are never written here: supply them at run time.'];
  for (const entry of ENV.filter(item => item.example)) lines.push('', `# ${entry.meaning} ${entry.default}`, `${entry.name}=`);
  return `${lines.join('\n')}\n`;
}

function docsText() {
  const lines = ['# Configuration', '', `<!-- ${generatedNote} -->`, '',
    'Chausar reads these environment variables. None is needed to run the desktop app: it sets the ones it uses itself. Someone running the local server or the hosted server from source may set the others; `.env.example` lists the usual ones. Data folders must be absolute paths outside the code folder.',
    '', 'Read by: desktop (the Electron app), worker (its engine process), server (the local web server), hosted (the hosted server), engine (any of them), child (a process Chausar starts and gives the variable to), scripts (build, test and release scripts), ci (the GitHub workflows). A secret is never written in a file in this repository.',
    '', '| Variable | What it does | When unset | Read by |', '|---|---|---|---|'];
  for (const entry of ENV) lines.push(`| \`${entry.name}\`${entry.secret ? ' (secret)' : ''} | ${html(entry.meaning)} | ${html(entry.default)} | ${entry.readers.join(', ')} |`);
  return `${lines.join('\n')}\n`;
}

const outputs = [['.env.example', exampleText()], ['docs/configuration.md', docsText()]];
if (mode[0] === '--write') {
  for (const [path, text] of outputs) { await mkdir(dirname(join(root, path)), { recursive: true }); await writeFile(join(root, path), text); }
  process.stdout.write(`Wrote .env.example and docs/configuration.md from ${ENV.length} variables.\n`);
  process.exit(0);
}

const problems = [];
for (const [path, text] of outputs) {
  const current = await readFile(join(root, path), 'utf8').catch(() => null);
  if (current === null || current.replace(/\r\n/g, '\n') !== text) problems.push(`${path} is not current: run node scripts/env-docs.mjs --write`);
}
const listed = new Set([...ENV.map(entry => entry.name), ...NOT_ENV]);
const unlisted = new Map();
for (const area of AREAS) {
  for (const file of await walk(join(root, area))) {
    const path = relative(root, file).replaceAll('\\', '/');
    if (SKIP_FILES.has(path)) continue;
    for (const [name] of (await readFile(file, 'utf8')).matchAll(/\bCHAUSAR_[A-Z0-9]+(?:_[A-Z0-9]+)*\b/g)) if (!listed.has(name) && !unlisted.has(name)) unlisted.set(name, path);
  }
}
for (const [name, path] of [...unlisted].sort()) problems.push(`${name} (${path}) is read but not listed in platform/runtime/config/env.ts`);
if (problems.length) {
  process.stderr.write(`${problems.join('\n')}\n`);
  process.exitCode = 1;
} else process.stdout.write(`${ENV.length} variables listed; .env.example and docs/configuration.md are current.\n`);
