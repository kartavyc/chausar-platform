import { contractDeclarations } from './contract-types.mjs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_METHODS, RENDERER_METHODS } from '../platform/runtime/method-registry.ts';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const header = '// Generated by scripts/gen-contract.mjs. Do not edit.\n';
export async function contractArtifacts() {
  const names = [...RENDERER_METHODS];
  const declaration = await readFile(join(root, 'app/desktop/ipc-contract.d.cts'), 'utf8');
  const tuple = /export const METHODS:\s*readonly\s*\[[\s\S]*?\];/;
  if (!tuple.test(declaration)) throw new Error('The desktop declaration needs its method tuple.');
  return new Map([
    ['app/ui/src/engine/contract.gen.ts', contractDeclarations()],
    ['app/desktop/engine-methods.cjs', header + "'use strict';\nmodule.exports = Object.freeze(" + JSON.stringify(ALL_METHODS, null, 2) + ');\n'],
    ['app/desktop/ipc-methods.cjs', `${header}'use strict';\nmodule.exports = Object.freeze(${JSON.stringify(names, null, 2)});\n`],
    ['app/desktop/ipc-contract.d.cts', declaration.replace(tuple, `export const METHODS: readonly ${JSON.stringify(names)};`).replace(/\r\n/g, '\n')],
    ['app/ui/src/engine/methods.gen.ts', `${header}export const RENDERER_METHOD_NAMES = ${JSON.stringify(names, null, 2)} as const;\nexport type RendererMethod = typeof RENDERER_METHOD_NAMES[number];\n`],
  ]);
}
export async function generateContract({ outputRoot = root } = {}) {
  for (const [relative, content] of await contractArtifacts()) {
    const file = join(outputRoot, relative);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
export async function checkGenerated({ outputRoot = root } = {}) {
  const differences = [];
  for (const [relative, expected] of await contractArtifacts()) {
    const actual = await readFile(join(outputRoot, relative), 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error; });
    if (actual.replace(/\r\n/g, '\n') === expected) continue;
    const names = text => new Set([...text.matchAll(/["']([a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+)["']/g)].map(row => row[1]));
    const before = names(actual), after = names(expected);
    const changed = [...new Set([...before, ...after])].filter(name => before.has(name) !== after.has(name));
    differences.push(`${relative}: ${changed.length ? changed.join(', ') : 'generated formatting differs'}`);
  }
  return differences;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.length === 1 && args[0] !== '--check') throw new Error('Use node scripts/gen-contract.mjs [--check].');
  if (args[0] === '--check') {
    const differences = await checkGenerated();
    if (differences.length) { process.stderr.write(`${differences.join('\n')}\n`); process.exitCode = 1; }
  } else await generateContract();
}
